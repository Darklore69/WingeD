    private fun getHighlightColor(targetColor: Int): Int {
        val invert = isNight() && prefs.getBoolean("invert", true)
        return if (invert) {
            val s = -0.88f
            val t = 235f
            val r = ((Color.red(targetColor) - t) / s).toInt().coerceIn(0, 255)
            val g = ((Color.green(targetColor) - t) / s).toInt().coerceIn(0, 255)
            val b = ((Color.blue(targetColor) - t) / s).toInt().coerceIn(0, 255)
            Color.argb(180, r, g, b)
        } else {
            Color.argb(180, Color.red(targetColor), Color.green(targetColor), Color.blue(targetColor))
        }
    }

    private fun renderHighlights() {
        val renderList = currentHighlights.map {
            androidx.pdf.Highlight(it.area, getHighlightColor(it.targetColor))
        }
        fragment.pdfViewRef?.setHighlights(renderList)
    }

    fun loadHighlights(rawUri: Uri) {
        val saved = prefs.getString(highlightKey(rawUri), null) ?: ""
        currentHighlights = HighlightStorage.deserialize(saved).toMutableList()
        renderHighlights()
        updateClearHighlightsButton()
    }

    private fun saveHighlights(rawUri: Uri) {
        prefs.edit().putString(highlightKey(rawUri), HighlightStorage.serialize(currentHighlights)).apply()
        updateClearHighlightsButton()
    }

    fun clearAllHighlights() {
        val rawUri = currentRawUri
        currentHighlights.clear()
        fragment.pdfViewRef?.setHighlights(emptyList())
        if (rawUri != null) {
            prefs.edit().remove(highlightKey(rawUri)).apply()
        }
        updateClearHighlightsButton()
        Toast.makeText(this, "Highlights cleared", Toast.LENGTH_SHORT).show()
    }

    private fun updateClearHighlightsButton() {
        if (::btnClearHighlights.isInitialized) {

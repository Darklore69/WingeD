    private inner class IndexAdapter : ArrayAdapter<TocEntry>(this@MainActivity, 0) {
        override fun getView(position: Int, convertView: View?, parent: ViewGroup): View {
            val v = convertView ?: layoutInflater.inflate(R.layout.item_index, parent, false)
            val e = getItem(position)!!
            val t = v.findViewById<TextView>(R.id.idxTitle)
            val p = v.findViewById<TextView>(R.id.idxPage)
            t.text = e.title
            t.setPadding(dp(16 + e.level * 16), dp(16), dp(8), dp(16))
            
            var isActive = false
            if (position < count) {
                val currentE = getItem(position)
                val nextE = if (position + 1 < count) getItem(position + 1) else null
                if (currentE != null && currentPage >= currentE.page && (nextE == null || currentPage < nextE.page)) {
                    isActive = true
                }
            }

            if (isActive) {
                val typedValue = android.util.TypedValue()
                theme.resolveAttribute(android.R.attr.colorPrimary, typedValue, true)
                val primaryColor = typedValue.data
                v.setBackgroundColor(primaryColor and 0x33FFFFFF)
                t.setTextColor(primaryColor)
                p.setTextColor(primaryColor)
                t.setTypeface(Typeface.create("sans-serif-medium", Typeface.BOLD))
            } else {
                v.setBackgroundResource(0)
                val typedValue = android.util.TypedValue()
                theme.resolveAttribute(com.google.android.material.R.attr.colorOnSurface, typedValue, true)
                t.setTextColor(typedValue.data)
                theme.resolveAttribute(com.google.android.material.R.attr.colorOnSurfaceVariant, typedValue, true)
                p.setTextColor(typedValue.data)
                
                if (e.level == 0) {
                    t.setTypeface(Typeface.create("sans-serif-medium", Typeface.NORMAL))
                } else {
                    t.setTypeface(Typeface.create("sans-serif", Typeface.NORMAL))
                }
            }
            
            p.text = (e.page + 1).toString()
            return v
        }
    }

    private fun indexKey(rawUri: Uri) = rawUri.toString().hashCode()

    private fun startIndex(rawUri: Uri, fileUri: Uri, force: Boolean) {
        indexToken.set(true)
        val token = AtomicBoolean(false)
        indexToken = token

        val key = indexKey(rawUri)
        if (!force) {
            val cached = prefs.getString("idx_$key", null)
            if (cached != null) {
                entries = IndexBuilder.deserialize(cached)
                autoGenerated = prefs.getBoolean("idxauto_$key", false)
                refreshDrawer()
                return
            }
        }

        entries = emptyList()
        indexAdapter.clear()
        indexStatus.text = "Reading contents…"

        Thread {
            try {
                val result = IndexBuilder.build(
                    applicationContext, fileUri, { token.get() }
                ) { page, total ->
                    if (page % 10 == 0 || page == total) {
                        runOnUiThread {
                            if (!token.get()) indexStatus.text = "Building index… page $page of $total"
                        }
                    }
                }
                runOnUiThread {
                    if (token.get() || currentRawUri != rawUri) return@runOnUiThread
                    entries = result.entries
                    autoGenerated = result.auto
                    prefs.edit()
                        .putString("idx_$key", IndexBuilder.serialize(result.entries))
                        .putBoolean("idxauto_$key", result.auto)
                        .apply()
                    refreshDrawer()
                }
            } catch (t: Throwable) {
                runOnUiThread {
                    if (!token.get()) {
                        entries = emptyList()
                        indexAdapter.clear()
                        indexStatus.text = "Couldn't build an index for this PDF"
                    }
                }
            }
        }.start()
    }

    private fun refreshDrawer() {
        indexAdapter.clear()
        indexAdapter.addAll(entries)
        val n = entries.size
        indexStatus.text = when {
            n == 0 -> "No headings found in this PDF"
            autoGenerated -> "$n entries · built automatically from headings (may be imperfect)"
            else -> "$n entries · from the PDF's own contents"
        }
        updateBookmarkRow()
    }


        }
    }

    fun applyHighlight(targetColor: Int) {
        val pdfView = fragment.pdfViewRef ?: return
        val selection = getPdfSelection(pdfView)
        if (selection == null) {
            Toast.makeText(this, "Select text to highlight", Toast.LENGTH_SHORT).show()
            return
        }

        val bounds = getSelectionBounds(selection)
        if (bounds.isEmpty()) {
            Toast.makeText(this, "Select text to highlight", Toast.LENGTH_SHORT).show()
            return
        }

        val selectedPdfRects = bounds.filterIsInstance<androidx.pdf.PdfRect>()
        var addedCount = 0

        val overlapping = currentHighlights.filter { existing ->
            selectedPdfRects.any { sel ->
                existing.area.pageNum == sel.pageNum &&
                RectF.intersects(
                    RectF(existing.area.left, existing.area.top, existing.area.right, existing.area.bottom),
                    RectF(sel.left, sel.top, sel.right, sel.bottom)
                )
            }
        }
        currentHighlights.removeAll(overlapping)

        for (pdfRect in selectedPdfRects) {
            currentHighlights.add(SavedHighlight(pdfRect, targetColor))
            addedCount++
        }

        if (addedCount > 0 || overlapping.isNotEmpty()) {
            renderHighlights()
            currentRawUri?.let { saveHighlights(it) }
            Toast.makeText(this, "Text highlighted", Toast.LENGTH_SHORT).show()
        }

        highlightPalette.visibility = View.GONE
        pdfView.clearCurrentSelection()
    }

    fun removeHighlightAtSelection() {
        val pdfView = fragment.pdfViewRef ?: return
        val selection = getPdfSelection(pdfView) ?: return
        val bounds = getSelectionBounds(selection)
        val selectedPdfRects = bounds.filterIsInstance<androidx.pdf.PdfRect>()

        val overlapping = currentHighlights.filter { existing ->
            selectedPdfRects.any { sel ->
                existing.area.pageNum == sel.pageNum &&
                RectF.intersects(
                    RectF(existing.area.left, existing.area.top, existing.area.right, existing.area.bottom),
                    RectF(sel.left, sel.top, sel.right, sel.bottom)
                )
            }
        }

        if (overlapping.isNotEmpty()) {
            currentHighlights.removeAll(overlapping)
            renderHighlights()
            currentRawUri?.let { saveHighlights(it) }
            Toast.makeText(this, "Highlight removed", Toast.LENGTH_SHORT).show()
        }
        highlightPalette.visibility = View.GONE
        pdfView.clearCurrentSelection()
    }

    fun setupPdfViewSelectionMenu(pdfView: androidx.pdf.view.PdfView) {
        try {
            val field = androidx.pdf.view.PdfView::class.java.getDeclaredField("selectionActionModeCallback")
            field.isAccessible = true
            val originalCallback = field.get(pdfView) as? ActionMode.Callback
            if (originalCallback != null) {
                val wrappedCallback = object : ActionMode.Callback2() {
                    override fun onCreateActionMode(mode: ActionMode?, menu: Menu?): Boolean {
                        val m = if (menu != null) wrapMenu(menu) else null
                        val res = originalCallback.onCreateActionMode(mode, m)
                        if (menu != null) addMarkMenuItem(menu)
                        return res
                    }

                    override fun onPrepareActionMode(mode: ActionMode?, menu: Menu?): Boolean {
                        val m = if (menu != null) wrapMenu(menu) else null
                        val res = originalCallback.onPrepareActionMode(mode, m)
                        if (menu != null) addMarkMenuItem(menu)
                        return res
                    }

                    override fun onActionItemClicked(mode: ActionMode?, item: MenuItem?): Boolean {
                        if (item?.itemId == R.id.btnMarkText) {
                            applyHighlight(Color.rgb(255, 255, 0))
                            mode?.finish()
                            return true
                        }
                        return originalCallback.onActionItemClicked(mode, item)
                    }

                    override fun onDestroyActionMode(mode: ActionMode?) {
                        originalCallback.onDestroyActionMode(mode)
                    }

                    override fun onGetContentRect(mode: ActionMode?, view: View?, outRect: Rect?) {
                        if (originalCallback is ActionMode.Callback2) {
                            originalCallback.onGetContentRect(mode, view, outRect)
                        } else {
                            super.onGetContentRect(mode, view, outRect)
                        }
                    }
                }
                field.set(pdfView, wrappedCallback)
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }

        try {
            val listenerClass = Class.forName("androidx.pdf.view.PdfView${'$'}OnSelectionChangedListener")
            val proxy = java.lang.reflect.Proxy.newProxyInstance(
                listenerClass.classLoader,
                arrayOf(listenerClass)
            ) { _, method, args ->
                if (method.name == "onSelectionChanged") {
                    val selection = args?.getOrNull(1) ?: args?.getOrNull(0)
                    val hasSelection = selection != null && getSelectionBounds(selection).isNotEmpty()
                    runOnUiThread {
                        if (::highlightPalette.isInitialized) {
                            highlightPalette.visibility = if (hasSelection) View.VISIBLE else View.GONE
                        }
                    }
                }
                null
            }
            val addListenerMethod = pdfView.javaClass.methods.firstOrNull { it.name == "addOnSelectionChangedListener" }
            addListenerMethod?.invoke(pdfView, proxy)
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }

    private fun getPdfSelection(pdfView: Any): Any? {
        return try {
            val method = pdfView.javaClass.methods.firstOrNull { it.name == "getCurrentSelection" || it.name.startsWith("getCurrentSelection") }
            method?.isAccessible = true
            method?.invoke(pdfView)
        } catch (_: Exception) {
            null
        }
    }

    @Suppress("UNCHECKED_CAST")
    private fun getSelectionBounds(selection: Any): List<Any> {
        return try {
            val method = selection.javaClass.methods.firstOrNull { it.name == "getBounds" }
            method?.isAccessible = true
            (method?.invoke(selection) as? List<Any>) ?: emptyList()
        } catch (_: Exception) {
            emptyList()
        }
    }

    override fun onWindowStartingActionMode(callback: ActionMode.Callback?): ActionMode? {
        val wrapped = wrapActionModeCallback(callback)
        return super.onWindowStartingActionMode(wrapped)
    }

    override fun onWindowStartingActionMode(callback: ActionMode.Callback?, type: Int): ActionMode? {
        val wrapped = wrapActionModeCallback(callback)
        return super.onWindowStartingActionMode(wrapped, type)
    }

    private fun wrapActionModeCallback(callback: ActionMode.Callback?): ActionMode.Callback? {
        if (callback == null) return null
        return object : ActionMode.Callback2() {
            override fun onCreateActionMode(mode: ActionMode?, menu: Menu?): Boolean {
                val m = if (menu != null) wrapMenu(menu) else null
                val created = callback.onCreateActionMode(mode, m)
                if (menu != null) addMarkMenuItem(menu)
                return created
            }

            override fun onPrepareActionMode(mode: ActionMode?, menu: Menu?): Boolean {
                val m = if (menu != null) wrapMenu(menu) else null
                val prepared = callback.onPrepareActionMode(mode, m)
                if (menu != null) addMarkMenuItem(menu)
                return prepared
            }

            override fun onActionItemClicked(mode: ActionMode?, item: MenuItem?): Boolean {
                if (item?.itemId == R.id.btnMarkText) {
                    applyHighlight(Color.rgb(255, 255, 0))
                    mode?.finish()
                    return true
                }
                return callback.onActionItemClicked(mode, item)
            }

            override fun onDestroyActionMode(mode: ActionMode?) {
                callback.onDestroyActionMode(mode)
            }

            override fun onGetContentRect(mode: ActionMode?, view: View?, outRect: Rect?) {
                if (callback is ActionMode.Callback2) {
                    callback.onGetContentRect(mode, view, outRect)
                } else {
                    super.onGetContentRect(mode, view, outRect)
                }
            }
        }
    }

    private fun wrapMenu(menu: Menu): Menu {
        val handler = Handler(Looper.getMainLooper())
        val ensureMark = Runnable { addMarkMenuItem(menu) }

        ensureMark.run()
        handler.post(ensureMark)
        handler.postDelayed(ensureMark, 100)
        handler.postDelayed(ensureMark, 300)

        return object : Menu by menu {
            override fun clear() {
                menu.clear()
                ensureMark.run()
            }

            override fun add(title: CharSequence?): MenuItem {
                val item = menu.add(title)
                handler.post(ensureMark)
                return item
            }

            override fun add(titleRes: Int): MenuItem {
                val item = menu.add(titleRes)
                handler.post(ensureMark)
                return item
            }

            override fun add(groupId: Int, itemId: Int, order: Int, title: CharSequence?): MenuItem {
                val item = menu.add(groupId, itemId, order, title)
                handler.post(ensureMark)
                return item
            }

            override fun add(groupId: Int, itemId: Int, order: Int, titleRes: Int): MenuItem {
                val item = menu.add(groupId, itemId, order, titleRes)
                handler.post(ensureMark)
                return item
            }
        }
    }

    private fun addMarkMenuItem(menu: Menu?) {
        if (menu != null && menu.findItem(R.id.btnMarkText) == null) {
            menu.add(Menu.NONE, R.id.btnMarkText, 0, "Mark")
                .setIcon(R.drawable.ic_highlight)
                .setShowAsAction(MenuItem.SHOW_AS_ACTION_ALWAYS or MenuItem.SHOW_AS_ACTION_WITH_TEXT)
        }
    }

    private fun updateMarkIcon() {
        val marked = bookmarkedPage >= 0 && bookmarkedPage == currentPage
        btnMark.setImageResource(
            if (marked) R.drawable.ic_bookmark_filled else R.drawable.ic_bookmark_outline
        )
    }

    override fun onViewport(firstVisible: Int, pageLocations: SparseArray<RectF>, viewHeight: Int) {
        lastPageLocations = pageLocations
        var page = firstVisible
        val mid = viewHeight / 2f
        for (i in 0 until pageLocations.size()) {
            val r = pageLocations.valueAt(i)
            if (r.top <= mid && r.bottom >= mid) {
                page = pageLocations.keyAt(i)
                break
            }
        }
        if (currentPage != page) {
            currentPage = page
            indexAdapter.notifyDataSetChanged()
        }
        pageIndicator.text = "Page ${page + 1}"
        pageIndicator.visibility = View.VISIBLE
        updateMarkIcon()

        if (pendingScrollPage >= 0) {
            val p = pendingScrollPage
            pendingScrollPage = -1
            fragment.pdfViewRef?.scrollToPage(p)
            return
        }

        val rect = if (bookmarkedPage >= 0) pageLocations.get(bookmarkedPage) else null
        if (rect == null) {
            corner.visibility = View.GONE
        } else {
            corner.translationX = rect.right - cornerSizePx
            corner.translationY = rect.top
            corner.visibility = View.VISIBLE
        }
    }

    private fun toggleBookmark() {
        val rawUri = currentRawUri
        if (rawUri == null) {
            Toast.makeText(this, "Open a PDF first", Toast.LENGTH_SHORT).show()
            return
        }
        if (bookmarkedPage == currentPage) {
            bookmarkedPage = -1
            prefs.edit().remove(bookmarkKey(rawUri)).apply()
            corner.visibility = View.GONE
            Toast.makeText(this, "Bookmark removed", Toast.LENGTH_SHORT).show()
        } else {
            bookmarkedPage = currentPage
            prefs.edit().putInt(bookmarkKey(rawUri), currentPage).apply()
            Toast.makeText(this, "Bookmarked page ${currentPage + 1}", Toast.LENGTH_SHORT).show()
        }
        updateMarkIcon()
        updateBookmarkRow()
    }

    private fun goToBookmark() {
        if (currentRawUri == null) {
            Toast.makeText(this, "Open a PDF first", Toast.LENGTH_SHORT).show()
            return
        }
        if (bookmarkedPage < 0) {
            Toast.makeText(this, "No bookmark set in this PDF", Toast.LENGTH_SHORT).show()
        } else {
            fragment.pdfViewRef?.scrollToPage(bookmarkedPage)
        }
    }

    private fun savePosition() {
        val rawUri = currentRawUri ?: return
        prefs.edit().putInt(positionKey(rawUri), currentPage).apply()
    }

    override fun onPause() {
        super.onPause()
        savePosition()
    }

    override fun dispatchTouchEvent(ev: android.view.MotionEvent): Boolean {
        if (ev.action == android.view.MotionEvent.ACTION_DOWN) {
            val menuItems = findViewById<View>(R.id.menuItems)
            if (menuItems.visibility == View.VISIBLE) {
                val rect = android.graphics.Rect()
                findViewById<View>(R.id.menuContainer).getGlobalVisibleRect(rect)
                if (!rect.contains(ev.rawX.toInt(), ev.rawY.toInt())) {
                    closeMenu()
                }
            }
        }
        
        if (!drawerLayout.isDrawerOpen(GravityCompat.START)) {
            if (gestureDetector.onTouchEvent(ev)) {
                val cancelEvent = android.view.MotionEvent.obtain(ev)
                cancelEvent.action = android.view.MotionEvent.ACTION_CANCEL
                super.dispatchTouchEvent(cancelEvent)
                cancelEvent.recycle()
                return true
            }
        }
        return super.dispatchTouchEvent(ev)
    }
